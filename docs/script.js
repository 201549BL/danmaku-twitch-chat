let currentLocale = "en";

function setLocale(locale) {
  if (!translations[locale]) return;
  currentLocale = locale;
  document.documentElement.lang = locale;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (translations[locale][key]) node.textContent = translations[locale][key];
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const key = node.dataset.i18nAria;
    if (translations[locale][key]) node.setAttribute("aria-label", translations[locale][key]);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    const key = node.dataset.i18nAlt;
    if (translations[locale][key]) node.setAttribute("alt", translations[locale][key]);
  });

  document.querySelectorAll("[data-locale]").forEach((button) => {
    button.setAttribute("aria-selected", String(button.dataset.locale === locale));
  });

  const currentLanguage = document.querySelector("[data-current-language]");
  if (currentLanguage) currentLanguage.textContent = locale === "ja" ? "日本語" : "English";

  const metadata = locale === "ja"
    ? {
        title: "Twitch用弾幕 — 動画上にチャットを表示",
        description: "全画面でもTwitchチャットを見逃さない。カスタマイズ可能でプライバシーに配慮したChrome用チャットオーバーレイ。",
      }
    : {
        title: "Danmaku for Twitch — Chat directly on the video",
        description: "Keep Twitch fullscreen without losing chat. Danmaku for Twitch puts customizable, private chat overlays directly on the video.",
      };

  document.title = metadata.title;
  document.querySelector('meta[name="description"]')?.setAttribute("content", metadata.description);

  try {
    localStorage.setItem("danmaku-site-locale", locale);
  } catch {
    // The language switch still works when storage is unavailable.
  }
}

const languageMenu = document.querySelector("[data-language-menu]");
const languageTrigger = document.querySelector("[data-language-trigger]");
const languagePopover = document.querySelector("[data-language-popover]");

function closeLanguageMenu() {
  if (!languageTrigger || !languagePopover) return;
  languageTrigger.setAttribute("aria-expanded", "false");
  languagePopover.hidden = true;
}

languageTrigger?.addEventListener("click", () => {
  if (!languagePopover) return;
  const willOpen = languagePopover.hidden;
  languagePopover.hidden = !willOpen;
  languageTrigger.setAttribute("aria-expanded", String(willOpen));
  if (willOpen) languagePopover.querySelector('[aria-selected="true"]')?.focus();
});

document.querySelectorAll("[data-locale]").forEach((button) => {
  button.addEventListener("click", () => {
    setLocale(button.dataset.locale);
    closeLanguageMenu();
    languageTrigger?.focus();
  });
});

document.addEventListener("click", (event) => {
  if (languageMenu && !languageMenu.contains(event.target)) closeLanguageMenu();
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closeLanguageMenu();
    languageTrigger?.focus();
  }
});

const header = document.querySelector("[data-header]");
const updateHeader = () => header?.classList.toggle("is-scrolled", window.scrollY > 18);
window.addEventListener("scroll", updateHeader, { passive: true });
updateHeader();

const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
if (prefersReducedMotion || !("IntersectionObserver" in window)) {
  document.querySelectorAll(".reveal").forEach((node) => node.classList.add("is-visible"));
} else {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  }, { threshold: 0.12 });

  document.querySelectorAll(".reveal").forEach((node) => observer.observe(node));
}

let preferredLocale = "en";
try {
  preferredLocale = localStorage.getItem("danmaku-site-locale") || (navigator.language.startsWith("ja") ? "ja" : "en");
} catch {
  preferredLocale = navigator.language.startsWith("ja") ? "ja" : "en";
}
setLocale(preferredLocale);
